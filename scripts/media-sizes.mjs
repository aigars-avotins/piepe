import {readdir,stat,writeFile} from 'node:fs/promises'
const sizes={}
for(const name of (await readdir('public/media')).sort()){
 const info=await stat('public/media/'+name)
 if(info.isFile())sizes['/media/'+name]=info.size
}
await writeFile('src/media-sizes.ts','// Generated by scripts/media-sizes.mjs. Cloudflare ASSETS omits Content-Length.\nexport const mediaSizes: Record<string, number> = '+JSON.stringify(sizes,null,2)+'\n')
